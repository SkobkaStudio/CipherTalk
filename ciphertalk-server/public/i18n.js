  const STORAGE_KEY = 'ciphertalk_lang';
  let lang = 'ru';

  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && DICT[saved]) lang = saved;
  } catch (e) { /* localStorage может быть недоступен */ }

  function t(key, vars) {
    const table = DICT[lang] || DICT.ru;
    let value = table[key];
    if (value === undefined) value = DICT.ru[key];
    if (value === undefined) return key;
    if (vars) {
      Object.keys(vars).forEach(name => {
        value = value.split('{' + name + '}').join(vars[name]);
      });
    }
    return value;
  }

  function getLang() {
    return lang;
  }

  function setLang(next) {
    if (!DICT[next]) return;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (e) { /* ignore */ }
    document.documentElement.setAttribute('lang', next);
    applyI18n();
  }

  function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
      el.innerHTML = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-text]').forEach(el => {
      el.textContent = t(el.dataset.i18nText);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = t(el.dataset.i18nTitle);
    });
  }

  global.I18N = { t, getLang, setLang, applyI18n, dict: DICT };
